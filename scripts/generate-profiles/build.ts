import type { ProfileDefinition } from "./definition";
import type { SignatureEvidence } from "./evidence";
import type { RomHashes } from "./hashes";
import { requireSymbol, type SymbolInfo } from "./sym";

const hex = (value: number, digits = 8) =>
  `0x${value.toString(16).padStart(digits, "0")}`;

function littleEndian(value: number): string {
  const bytes = [
    value & 0xff,
    (value >>> 8) & 0xff,
    (value >>> 16) & 0xff,
    (value >>> 24) & 0xff,
  ];
  return bytes.map((b) => b.toString(16).padStart(2, "0")).join("");
}

function tableOf(
  symbols: ReadonlyMap<string, SymbolInfo>,
  table: { readonly symbol: string; readonly entrySize: number },
) {
  const symbol = requireSymbol(symbols, table.symbol);
  if (symbol.size % table.entrySize !== 0) {
    throw new Error(
      `${table.symbol} is ${symbol.size} bytes, not a multiple of ${table.entrySize}`,
    );
  }
  return { base: hex(symbol.address), count: symbol.size / table.entrySize };
}

/** Builds one profile file as plain JSON. A pure function of the definition, the symbol file, the hashes and the signature evidence level. */
export function buildProfile(
  definition: ProfileDefinition,
  symbols: ReadonlyMap<string, SymbolInfo>,
  hashes: RomHashes,
  evidence: SignatureEvidence,
): Record<string, unknown> {
  const addresses: Record<string, unknown> = {};
  for (const entry of definition.addresses) {
    const at = hex(requireSymbol(symbols, entry.symbol).address);
    addresses[entry.key] = entry.pointer ? { ptr: at, offset: "0x0" } : at;
  }
  return {
    id: definition.id,
    kind: "official",
    name: definition.name,
    dataFormat: definition.dataFormat,
    language: "en",
    artVersion: definition.artVersion,
    addresses,
    constants: {},
    identify: {
      sha1: hashes.sha1,
      crc32: hashes.crc32,
      header: definition.identify.header,
      signature: definition.identify.signature.map((word) => ({
        address: hex(word.address),
        bytes: littleEndian(requireSymbol(symbols, word.symbol).address),
      })),
    },
    trainerTables: {
      trainers: tableOf(symbols, definition.trainerTables.trainers),
      classNames: tableOf(symbols, definition.trainerTables.classNames),
      money: tableOf(symbols, definition.trainerTables.money),
    },
    fixture: definition.fixture,
    provenance: {
      kind: "pret",
      ...definition.source,
      signatureEvidence: evidence,
    },
  };
}

export function renderProfile(profile: Record<string, unknown>): string {
  return `${JSON.stringify(profile, null, 2)}\n`;
}

/** The generated barrel the server imports. Sorted by ID so the output never depends on definition order. */
export function renderIndex(ids: readonly string[]): string {
  const sorted = [...ids].sort();
  const names = sorted.map((id) => ({
    id,
    name: id.replace(/[^a-zA-Z0-9]+([a-zA-Z0-9])/g, (_, c: string) =>
      c.toUpperCase(),
    ),
  }));
  const imports = names.map(
    ({ id, name }) => `import ${name} from "./${id}.json";`,
  );
  return [
    "// Generated by `bun run generate:profiles`. Do not edit.",
    ...imports,
    "",
    `export const builtinProfiles: readonly unknown[] = [${names.map((n) => n.name).join(", ")}];`,
    "",
  ].join("\n");
}
